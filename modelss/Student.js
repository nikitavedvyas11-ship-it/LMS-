const mongoose=require('mongoose');
const studentSchema=new mongoose.Schema(
    {
        name:{
            type:String,
            required:true,
            trim:true
        },
        email:{
            type:String,
            required:true,
            trim:true,
            unique:true,
            lowercase:true
        },
        password:{
            type:String,
            required:true,
            select:false
        },
        phone:{
            type:String,
            required:true,
            unique:true,
            trim:true
        },
        dob:{
            type:Date,
            required:true
        },
        gender:{
            type:String,
            enum:['male','female','other'],
            required:true
        },
        address:{
            street:{
                type:String,
                required:true,
                trim:true
            },
            city:{
                type:String,
                required:true,
                trim:true
            },
            state:{
                type:String,
                required:true,
                trim:true
            },
            country:{
                type:String,
                required:true,
                trim:true
            }
        },
        enrollment_number:{
            type:String,
            required:true,
            unique:true,
            trim:true
        },
        department:{
            type:String, 
            required:true,
            trim:true
        },
        semester:{
            type:Number,
            required:true,  
            min:1,
            max:12          
        },
        admission_date:{
            type:Date,
            required:true,
        },
        status:{
            type:String,
            enum:['active','dropout','inactive','passout'],
            default:'active'
        },
        role:{
            type:String,
            default:'student'
        }
    }, { timestamps: true }
)
module.exports=mongoose.model('Student',studentSchema);